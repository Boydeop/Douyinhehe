"""Recoverable, licensed local video-edit batch; no hidden remote publishing.

The manifest is explicitly supplied by the user, never scraped or generated by
circumventing platform restrictions. All outputs have creator attribution and
local provenance evidence. Re-renders are atomic at the media-engine boundary.
"""

from __future__ import annotations

import csv
import hashlib
import json
import re
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Callable

from .core import LicenseGrant, Store, file_sha256, now_utc
from .downloader import parse_douyin_urls
from .media import EditPreset, probe_video, render_video

ALLOWED_EXTENSIONS = {".mp4", ".mov", ".mkv", ".webm"}
REQUIRED_COLUMNS = ("file", "original_url")


@dataclass(frozen=True)
class BatchItem:
    file: Path
    original_url: str
    creator: str
    evidence: str
    commercial: bool
    derivative: bool
    platforms: str = "facebook,tiktok,youtube,instagram,threads"
    niche: str = ""
    fit: str = "crop"
    cta: str = ""
    subtitle: Path | None = None
    brightness: float = 0
    contrast: float = 1
    saturation: float = 1
    expires_on: str = ""
    evidence_file: Path | None = None
    evidence_sha256: str = ""
    masks: str = ""
    trim_start: float = 0.0
    trim_end: float | None = None

    def validate(self) -> None:
        LicenseGrant(self.original_url, self.creator, self.evidence,
                     self.commercial, self.derivative, self.platforms,
                     self.expires_on, str(self.evidence_file or ""), self.evidence_sha256).validate()
        if not self.original_url.startswith("local://") and parse_douyin_urls(self.original_url) != [self.original_url]:
            raise ValueError("Nguồn phải là URL Douyin HTTPS hoặc local:// cho video tự quay.")
        if not self.file.is_file() or self.file.suffix.lower() not in ALLOWED_EXTENSIONS:
            raise ValueError(f"File video không tồn tại hoặc không hỗ trợ: {self.file}")
        self.preset().validate()

    def preset(self) -> EditPreset:
        from .studio_engine import parse_regions
        return EditPreset(creator="", original_url=self.original_url,
                          fit=self.fit, cta=self.cta, subtitle=self.subtitle,
                          brightness=self.brightness, contrast=self.contrast,
                          saturation=self.saturation, masks=parse_regions(self.masks),
                          trim_start=self.trim_start, trim_end=self.trim_end)

    def payload(self) -> dict:
        result = asdict(self)
        for key in ("file", "subtitle"):
            result[key] = str(result[key]) if result[key] is not None else None
        for key in ("creator", "evidence", "expires_on", "evidence_file", "evidence_sha256"):
            result.pop(key, None)
        result["creator"] = ""
        result["evidence"] = ""
        return result

    @classmethod
    def from_payload(cls, row: dict) -> "BatchItem":
        row = dict(row)
        row.setdefault("creator", "")
        row.setdefault("evidence", "")
        row["file"] = Path(row["file"])
        if row.get("subtitle"):
            row["subtitle"] = Path(row["subtitle"])
        if row.get("evidence_file"):
            row["evidence_file"] = Path(row["evidence_file"])
        return cls(**row)


def _bool(value: object, key: str) -> bool:
    if isinstance(value, bool):
        return value
    if str(value).strip().lower() in {"true", "yes", "1", "có"}:
        return True
    if str(value).strip().lower() in {"false", "no", "0", "không", ""}:
        return False
    raise ValueError(f"{key} phải là true/false")


def read_manifest(path: Path, *, limit: int = 500) -> list[BatchItem]:
    """Read explicit CSV/JSON manifest; all relative media paths use its directory."""
    manifest = Path(path).resolve()
    if not manifest.is_file() or manifest.suffix.lower() not in {".csv", ".json"}:
        raise ValueError("Cần file danh sách CSV hoặc JSON có thật.")
    if manifest.stat().st_size > 3_000_000:
        raise ValueError("Manifest lớn hơn giới hạn 3 MB.")
    if manifest.suffix.lower() == ".csv":
        with manifest.open("r", encoding="utf-8-sig", newline="") as stream:
            reader = csv.DictReader(stream)
            if not reader.fieldnames or not set(REQUIRED_COLUMNS).issubset(reader.fieldnames):
                raise ValueError("CSV thiếu các cột: " + ", ".join(REQUIRED_COLUMNS))
            rows = list(reader)
    else:
        rows = json.loads(manifest.read_text(encoding="utf-8-sig"))
    if not isinstance(rows, list) or not 1 <= len(rows) <= limit:
        raise ValueError(f"Cần 1 đến {limit} dòng dữ liệu.")
    result = []
    for i, row in enumerate(rows, 1):
        if not isinstance(row, dict):
            raise ValueError(f"Dòng {i} phải là một object.")
        if not all(row.get(key) for key in REQUIRED_COLUMNS):
            raise ValueError(f"Dòng {i} thiếu file hoặc URL nguồn.")
        try:
            file = Path(row["file"])
            if not file.is_absolute():
                file = manifest.parent / file
            subtitle = Path(row["subtitle"]) if row.get("subtitle") else None
            if subtitle is not None and not subtitle.is_absolute():
                subtitle = manifest.parent / subtitle
            evidence_file = Path(row["evidence_file"]) if row.get("evidence_file") else None
            if evidence_file is not None and not evidence_file.is_absolute():
                evidence_file = manifest.parent / evidence_file
            item = BatchItem(
                file=file.resolve(), original_url=str(row["original_url"]).strip(),
                creator="", evidence="",
                commercial=_bool(row.get("commercial", False), "commercial"),
                derivative=_bool(row.get("derivative", False), "derivative"),
                platforms=str(row.get("platforms") or "facebook,tiktok,youtube,instagram,threads"),
                niche=str(row.get("niche") or ""), fit=str(row.get("fit") or "crop"),
                cta=str(row.get("cta") or ""), subtitle=subtitle,
                brightness=float(row.get("brightness") or 0),
                contrast=float(row.get("contrast") or 1),
                saturation=float(row.get("saturation") or 1),
                expires_on="", evidence_file=None, evidence_sha256="",
                masks=(json.dumps(row["masks"]) if isinstance(row.get("masks"), list)
                       else str(row.get("masks") or "")),
                trim_start=float(row.get("trim_start") or 0),
                trim_end=(float(row["trim_end"]) if row.get("trim_end") not in (None, "", "0") else None),
            )
            item.validate()
            result.append(item)
        except (ValueError, TypeError, KeyError) as exc:
            raise ValueError(f"Dòng {i}: {exc}") from exc
    return result


def job_key(item: BatchItem) -> str:
    encoded = json.dumps(item.payload(), ensure_ascii=False, sort_keys=True).encode("utf-8")
    return hashlib.sha256(b"douyinhehe-v2-render\x00" + encoded).hexdigest()


def enqueue_manifest(store: Store, path: Path) -> tuple[int, int]:
    items = read_manifest(path)
    return store.enqueue_renders([(job_key(item), item.payload()) for item in items])


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def run_queue(store: Store, outdir: Path, progress: Callable[[str], None] | None = None,
              *, max_jobs: int = 500) -> dict:
    """Process local render jobs once each. Failed jobs stay failed until retry."""
    outdir = Path(outdir).resolve()
    outdir.mkdir(parents=True, exist_ok=True)
    done = failed = 0
    for _ in range(max_jobs):
        job = store.claim_next_render()
        if job is None:
            break
        try:
            item = BatchItem.from_payload(json.loads(job["payload"]))
            item.validate()  # permissions and source can change since enqueue
            source_hash = _sha256(item.file)
            filename = re.sub(r"[^\w.-]", "_", item.file.stem, flags=re.UNICODE)[:64]
            dest = outdir / f"{filename}_{job['job_key'][:10]}.mp4"
            if progress:
                progress(f"#{job['id']} Render {item.file.name}")
            render_video(item.file, dest, item.preset(), progress)
            meta = probe_video(dest)
            sidecar = {
                "schema": "douyinhehe.provenance.v2", "created_at": now_utc(),
                "source_url": item.original_url, "commercial": item.commercial,
                "derivative": item.derivative, "platforms": item.platforms,
                "niche": item.niche, "source_sha256": source_hash,
                "output_sha256": _sha256(dest),
                "streams": [{"codec_type": s.get("codec_type"), "codec_name": s.get("codec_name"),
                             "width": s.get("width"), "height": s.get("height")}
                            for s in meta.get("streams", [])],
            }
            sidecar_path = dest.with_suffix(".provenance.json")
            sidecar_path.write_text(json.dumps(sidecar, ensure_ascii=False, indent=2), encoding="utf-8")
            store.finish_render(job["id"], str(dest), "")
            done += 1
        except Exception as exc:
            store.finish_render(job["id"], "", f"{type(exc).__name__}: {exc}"[:800])
            failed += 1
            if progress:
                progress(f"#{job['id']} lỗi: {type(exc).__name__}: {exc}")
    return {"done": done, "failed": failed, "pending": store.render_counts().get("pending", 0)}


def create_local_manifest(folder: Path, manifest: Path, *, creator: str = "", evidence: str = "",
                          rights_confirmed: bool = False, expires_on: str = "") -> Path:
    """Import self-shot or otherwise licensed local clips without a Douyin URL."""
    if not rights_confirmed:
        raise PermissionError("Phải xác nhận quyền dùng thương mại và biên tập video nguồn.")
    folder = Path(folder).resolve()
    if not folder.is_dir():
        raise ValueError("Cần thư mục video hợp lệ.")
    files = [p for p in sorted(folder.iterdir()) if p.is_file() and p.suffix.lower() in ALLOWED_EXTENSIONS]
    if not 1 <= len(files) <= 500:
        raise ValueError("Chỉ hỗ trợ từ 1 đến 500 video hợp lệ mỗi lần nhập.")
    rows = [{"file": str(path), "original_url": "local://" + _sha256(path),
             "commercial": True, "derivative": True} for path in files]
    dest = Path(manifest).resolve()
    if dest.suffix.lower() != ".json":
        raise ValueError("Manifest xuất cần đuôi .json.")
    # Only write after every grant passes validation.
    for row in rows:
        LicenseGrant(row["original_url"], "", "", True, True).validate()
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_suffix(".tmp")
    part.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    part.replace(dest)
    return dest
